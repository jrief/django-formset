import {build} from 'esbuild';
import parser from 'yargs-parser';

const buildOptions = parser(process.argv.slice(2), {
  boolean: ['debug'],
});

build({
  entryPoints: [
    'testapp/assets/formset-extensions/formset-extensions.ts',
  ],
  bundle: true,
  minify: !buildOptions.debug,
  sourcemap: buildOptions.debug,
  banner: {
    js: '// This file is generated by esbuild\n// !!!DO NOT EDIT!!!\n',
  },
  outdir: 'testapp/static/testapp/js',
  loader: {'.css': 'text'},
  target: ['es2022', 'chrome100', 'firefox100', 'safari15', 'edge100']
});
